export class SpriteBaker {
  public static bake(scene: Phaser.Scene) {
    for (const [key, data] of Object.entries(Sprites)) {
      if (!scene.textures.exists(key)) {
        scene.textures.generate(key, { data, pixelWidth: 1, pixelHeight: 1, palette: NESPalette });
      }
    }

    if (!scene.textures.exists('hangar_bg')) {
      const g = scene.add.graphics();
      g.fillStyle(0x111111, 1);
      g.fillRect(0, 0, 270, 480);
      g.lineStyle(2, 0x333333, 1);
      for (let y = 0; y < 480; y += 40) {
        g.moveTo(0, y);
        g.lineTo(270, y);
      }
      for (let x = 0; x < 270; x += 40) {
        g.moveTo(x, 0);
        g.lineTo(x, 480);
      }
      g.strokePath();
      g.generateTexture('hangar_bg', 270, 480);
      g.destroy();
    }
  }
}
